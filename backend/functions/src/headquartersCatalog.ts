export function initialHeadquartersCount(): number { return Allowed.size; }

export interface InitialHeadquartersLocation {
  countryCode: string;
  cityKey: string;
}

export function validateInitialHeadquarters(value: unknown): InitialHeadquartersLocation {
  if (typeof value !== "object" || value === null || Array.isArray(value) ||
      Object.keys(value).sort().join(",") !== "cityKey,countryCode")
    throw new CommandError("INVALID_ARGUMENT");

  const location = value as Record<string, unknown>;
  if (typeof location.countryCode !== "string" ||
      typeof location.cityKey !== "string" ||
      !/^[A-Z]{3}$/.test(location.countryCode) ||
      !/^[a-z0-9_-]{1,80}$/.test(location.cityKey))
    throw new CommandError("INVALID_ARGUMENT");

  if (!Allowed.has(location.countryCode + "|" + location.cityKey))
    throw new CommandError("INVALID_ARGUMENT");

  return { countryCode: location.countryCode, cityKey: location.cityKey };
}
